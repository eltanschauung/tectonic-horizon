#!/usr/bin/env python3
"""Reproduce the embedded CC0 terrain definitions from the recorded upstream checkout."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PIN = "0761b561062de01b701d2571401f625c31059a9a"
PACK = Path("src/main/resources/resourcepacks/tectonic")
KINDS = {"worldgen/density_function": "densities", "worldgen/noise": "noises",
         "worldgen/noise_settings": "settings", "dimension_type": "dimension_types"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    args = parser.parse_args()
    revision = subprocess.check_output(["git", "-C", str(args.checkout), "rev-parse", "HEAD"], text=True).strip()
    if revision != PIN:
        raise SystemExit(f"upstream checkout must be {PIN}")
    subprocess.run(["git", "-C", str(args.checkout), "diff", "--exit-code", "HEAD", "--", str(PACK)], check=True)
    lines = ["// Apollo's Tectonic 3.0.1 terrain definitions, CC0-1.0.",
             "// Generated by tools/import_terrain.py; see upstream.json."]
    hashes = {}
    for table, folder in [("BASE", "data"), ("MOD", "overlay.mod/data"), ("TALL", "overlay.increased_height/data")]:
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub const {table}: &[(&str, &str, &str)] = &[")
        for file in sorted((args.checkout / PACK / folder).rglob("*.json")):
            relative = file.relative_to(args.checkout / PACK / folder)
            namespace, *parts = relative.parts
            path = "/".join(parts)
            for kind, bundle in KINDS.items():
                if not path.startswith(kind + "/"):
                    continue
                raw = file.read_bytes()
                text = json.dumps(json.loads(raw), separators=(",", ":"), ensure_ascii=False)
                identifier = namespace + ":" + path[len(kind) + 1:-5]
                lines.append(f'    ({json.dumps(bundle)}, {json.dumps(identifier)}, r##"{text}"##),')
                hashes[str(file.relative_to(args.checkout))] = hashlib.sha256(raw).hexdigest()
                break
        lines.append("];")
    (ROOT / "mixins/tectonic_horizon/terrain.rs").write_text("\n".join(lines) + "\n")
    (ROOT / "upstream.json").write_text(json.dumps({"repository": "https://github.com/Apollounknowndev/tectonic",
        "revision": PIN, "version": "3.0.1", "license": "CC0-1.0", "files_sha256": hashes}, indent=2) + "\n")


if __name__ == "__main__":
    main()
